"""
Remove the "Generated by Claude Code" footer from GitHub posts.

A Claude Code cloud session writes to GitHub through a proxy. The proxy adds
this footer to the end of each issue, pull request, comment and review that
the session writes:

    ---
    _Generated by [Claude Code](https://claude.ai/code/...)_

No Claude Code setting turns it off (anthropics/claude-code#101004). So the
workflow .github/workflows/strip-claude-footer.yml runs this script with the
token of the workflow, which does not go through the proxy:

- On an event (an issue, comment, review or pull request that someone opens
  or edits), it removes the footer from that post.
- On a manual run (workflow_dispatch), it removes the footer from every
  issue, pull request, comment and review comment in the repository.

The script changes only a post that ends with the footer, and it removes only
the footer.
"""

import json
import os
import re
import urllib.request
from collections.abc import Iterator
from dataclasses import dataclass
from typing import Any, Literal

# The rule (---) and the footer line at the end of a post, with the blank
# lines around them. The link can include a session path.
_FOOTER = re.compile(
    r"\s*\n-{3,}\s*\n+_Generated by \[Claude Code\]\(https://claude\.ai/code[^)\s]*\)_\s*\Z"
)

type Method = Literal["PATCH", "PUT"]
type Json = Any  # a decoded GitHub REST API response


def strip_footer(body: str) -> str:
    """body without the footer at its end. A body without the footer, or
    with the footer anywhere but at the end, comes back unchanged."""
    return _FOOTER.sub("", body)


@dataclass(frozen=True)
class Post:
    """One GitHub post that has a body text."""

    url: str  # REST API URL that updates the post
    method: Method  # a review body takes PUT, every other post takes PATCH
    body: str


def _request(token: str, method: str, url: str, data: Json = None) -> Json:
    """Send one GitHub REST API request and return the decoded response."""
    request = urllib.request.Request(
        url,
        method=method,
        data=None if data is None else json.dumps(data).encode(),
        headers={
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        },
    )
    with urllib.request.urlopen(request) as response:
        return json.load(response)


def _pages(token: str, url: str) -> Iterator[Json]:
    """Every item of a paginated GitHub list endpoint."""
    page = 1
    while True:
        items = _request(token, "GET", f"{url}?state=all&per_page=100&page={page}")
        yield from items
        if len(items) < 100:
            return
        page += 1


def event_post(event_name: str, event: Json) -> Post | None:
    """The post of a webhook event, or None if the event has no post body."""
    match event_name:
        case "issue_comment" | "pull_request_review_comment":
            comment = event["comment"]
            return Post(comment["url"], "PATCH", comment["body"] or "")
        case "issues":
            issue = event["issue"]
            return Post(issue["url"], "PATCH", issue["body"] or "")
        case "pull_request_target":
            pull = event["pull_request"]
            return Post(pull["url"], "PATCH", pull["body"] or "")
        case "pull_request_review":
            review = event["review"]
            url = f"{event['pull_request']['url']}/reviews/{review['id']}"
            return Post(url, "PUT", review["body"] or "")
        case _:
            return None


def all_posts(token: str, repo_url: str) -> Iterator[Post]:
    """Every issue, pull request, issue comment and review comment."""
    for issue in _pages(token, f"{repo_url}/issues"):
        yield Post(issue["url"], "PATCH", issue["body"] or "")
    for comment in _pages(token, f"{repo_url}/issues/comments"):
        yield Post(comment["url"], "PATCH", comment["body"] or "")
    for comment in _pages(token, f"{repo_url}/pulls/comments"):
        yield Post(comment["url"], "PATCH", comment["body"] or "")


def clean(token: str, post: Post) -> bool:
    """Remove the footer from post. Return True if the post changed."""
    stripped = strip_footer(post.body)
    if stripped == post.body:
        return False
    _request(token, post.method, post.url, {"body": stripped})
    return True


def main() -> None:
    token = os.environ["GITHUB_TOKEN"]
    event_name = os.environ["GITHUB_EVENT_NAME"]
    repo_url = f"{os.environ['GITHUB_API_URL']}/repos/{os.environ['GITHUB_REPOSITORY']}"
    if event_name == "workflow_dispatch":
        posts = list(all_posts(token, repo_url))
    else:
        with open(os.environ["GITHUB_EVENT_PATH"]) as file:
            post = event_post(event_name, json.load(file))
        posts = [] if post is None else [post]
    changed = [post.url for post in posts if clean(token, post)]
    print(f"removed the footer from {len(changed)} of {len(posts)} posts")
    for url in changed:
        print(f"  {url}")


if __name__ == "__main__":
    main()
