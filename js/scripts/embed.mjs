// Write src/generated/car.ts: the car's MJCF, assets/neoracer.xml, as a
// string, so a browser bundle needs no file access to load the car, and the
// settings beside the model, assets/neoracer.json (neoracer_mujoco's
// twin.export.settings_json), as an object.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const xml = readFileSync(new URL('../../assets/neoracer.xml', import.meta.url), 'utf8');
const settings = JSON.parse(readFileSync(new URL('../../assets/neoracer.json', import.meta.url), 'utf8'));
mkdirSync(new URL('../src/generated/', import.meta.url), { recursive: true });
writeFileSync(
  new URL('../src/generated/car.ts', import.meta.url),
  '// Generated by scripts/embed.mjs from assets/neoracer.xml and assets/neoracer.json. Do not edit.\n' +
    `export const CAR_XML: string = ${JSON.stringify(xml)};\n` +
    `export const CAR_SETTINGS = ${JSON.stringify(settings, null, 2)} as const;\n`,
);
