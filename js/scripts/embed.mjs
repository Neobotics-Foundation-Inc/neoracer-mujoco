// Write src/generated/car.ts: the car's MJCF, assets/neoracer.xml, as a
// string, so a browser bundle needs no file access to load the car.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const xml = readFileSync(new URL('../../assets/neoracer.xml', import.meta.url), 'utf8');
mkdirSync(new URL('../src/generated/', import.meta.url), { recursive: true });
writeFileSync(
  new URL('../src/generated/car.ts', import.meta.url),
  `// Generated by scripts/embed.mjs from assets/neoracer.xml. Do not edit.\nexport const CAR_XML: string = ${JSON.stringify(xml)};\n`,
);
